// Command bundle builds the JS islands of the web UI (ADR 0012) without Node:
// it downloads the npm tarballs pinned in web/package-lock.json, verifies
// their sha512 integrity, unpacks them into a scratch node_modules and runs
// esbuild (as a Go library) on each island: web/editor.js (CodeMirror 6, the
// SQL editor) and web/charts.js (Apache ECharts, tree-shaken, the dashboards).
//
// The outputs (modules/web/static/editor.js and charts.js) are committed, so `just generate`
// and CI never need the network; run `just bundle` to rebuild it after
// changing web/ (the lockfile is the only source of versions).
package main

import (
	"archive/tar"
	"bytes"
	"compress/gzip"
	"crypto/sha512"
	"encoding/base64"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/evanw/esbuild/pkg/api"
)

// islands are the bundles to build: entry under web/, output under modules/web/static/.
var islands = []struct{ entry, out, banner string }{
	{"editor.js", "editor.js", "/* Generated by tools/bundle from tools/bundle/web (CodeMirror 6). Do not edit. */"},
	{"charts.js", "charts.js", "/* Generated by tools/bundle from tools/bundle/web (Apache ECharts 6, Apache-2.0). Do not edit. */"},
}

type lockfile struct {
	Packages map[string]struct {
		Resolved  string `json:"resolved"`
		Integrity string `json:"integrity"`
	} `json:"packages"`
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "bundle:", err)
		os.Exit(1)
	}
}

func run() error {
	src := filepath.FromSlash("tools/bundle/web")
	outDir := filepath.FromSlash("modules/web/static")
	if _, err := os.Stat(filepath.Join(src, "package-lock.json")); err != nil {
		return fmt.Errorf("run from the repo root (go run ./tools/bundle): %w", err)
	}
	cacheRoot, err := os.UserCacheDir()
	if err != nil {
		return err
	}
	cache := filepath.Join(cacheRoot, "duct-bundle")
	if err := os.MkdirAll(cache, 0o755); err != nil {
		return err
	}
	work, err := os.MkdirTemp(cache, "work-")
	if err != nil {
		return err
	}
	defer func() { _ = os.RemoveAll(work) }()

	raw, err := os.ReadFile(filepath.Join(src, "package-lock.json"))
	if err != nil {
		return err
	}
	var lock lockfile
	if err := json.Unmarshal(raw, &lock); err != nil {
		return err
	}
	for path, p := range lock.Packages {
		if path == "" {
			continue
		}
		if p.Resolved == "" || !strings.HasPrefix(p.Integrity, "sha512-") {
			return fmt.Errorf("%s: lockfile entry without resolved/sha512 integrity", path)
		}
		data, err := fetch(cache, p.Resolved, p.Integrity)
		if err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		if err := untar(data, filepath.Join(work, filepath.FromSlash(path))); err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
	}

	for _, isl := range islands {
		code, err := os.ReadFile(filepath.Join(src, isl.entry))
		if err != nil {
			return err
		}
		entry := filepath.Join(work, isl.entry)
		if err := os.WriteFile(entry, code, 0o644); err != nil {
			return err
		}
		res := api.Build(api.BuildOptions{
			EntryPoints:       []string{entry},
			AbsWorkingDir:     work,
			Bundle:            true,
			MinifyWhitespace:  true,
			MinifySyntax:      true,
			Format:            api.FormatIIFE,
			Target:            api.ES2020,
			Platform:          api.PlatformBrowser,
			LegalComments:     api.LegalCommentsNone,
			Write:             false,
			Outfile:           filepath.Join(work, isl.entry+".out.js"),
			Banner:            map[string]string{"js": isl.banner},
			Sourcemap:         api.SourceMapNone,
			MinifyIdentifiers: true,
		})
		if len(res.Errors) > 0 {
			for _, e := range res.Errors {
				fmt.Fprintln(os.Stderr, e.Text, e.Location)
			}
			return fmt.Errorf("esbuild failed on %s", isl.entry)
		}
		if len(res.OutputFiles) != 1 {
			return fmt.Errorf("expected one output file, got %d", len(res.OutputFiles))
		}
		dest := filepath.Join(outDir, isl.out)
		if err := os.MkdirAll(outDir, 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(dest, res.OutputFiles[0].Contents, 0o644); err != nil {
			return err
		}
		fmt.Printf("bundle: wrote %s (%d bytes)\n", dest, len(res.OutputFiles[0].Contents))
	}
	return nil
}

// fetch returns the tarball for url, from the cache when its integrity holds.
func fetch(cache, url, integrity string) ([]byte, error) {
	want, err := base64.StdEncoding.DecodeString(strings.TrimPrefix(integrity, "sha512-"))
	if err != nil {
		return nil, err
	}
	file := filepath.Join(cache, fmt.Sprintf("%x.tgz", want[:16]))
	if data, err := os.ReadFile(file); err == nil && sum(data) == string(want) {
		return data, nil
	}
	client := &http.Client{Timeout: 2 * time.Minute}
	resp, err := client.Get(url)
	if err != nil {
		return nil, err
	}
	defer func() { _ = resp.Body.Close() }()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("GET %s: %s", url, resp.Status)
	}
	data, err := io.ReadAll(resp.Body)
	if err != nil {
		return nil, err
	}
	if sum(data) != string(want) {
		return nil, fmt.Errorf("integrity mismatch for %s", url)
	}
	return data, os.WriteFile(file, data, 0o644)
}

func sum(b []byte) string {
	h := sha512.Sum512(b)
	return string(h[:])
}

// untar unpacks an npm tarball (files under "package/") into dest.
func untar(data []byte, dest string) error {
	gz, err := gzip.NewReader(bytes.NewReader(data))
	if err != nil {
		return err
	}
	tr := tar.NewReader(gz)
	for {
		h, err := tr.Next()
		if err == io.EOF {
			return nil
		}
		if err != nil {
			return err
		}
		if h.Typeflag != tar.TypeReg {
			continue
		}
		rel := strings.TrimPrefix(h.Name, "package/")
		target := filepath.Join(dest, filepath.FromSlash(rel))
		if !strings.HasPrefix(target, filepath.Clean(dest)+string(os.PathSeparator)) {
			return fmt.Errorf("unsafe path %q in tarball", h.Name)
		}
		if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
			return err
		}
		b, err := io.ReadAll(tr)
		if err != nil {
			return err
		}
		if err := os.WriteFile(target, b, 0o644); err != nil {
			return err
		}
	}
}
